-- Opt-in row-change auditing for the project's users, products, and orders tables.
-- Run as the database administrator after the schema exists: make audit-enable
-- Records INSERT/UPDATE/DELETE changes (not SELECT statements). Audit records
-- participate in the same transaction as the original change.

CREATE SCHEMA IF NOT EXISTS audit;
REVOKE ALL ON SCHEMA audit FROM PUBLIC;

CREATE TABLE IF NOT EXISTS audit.table_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_schema    TEXT NOT NULL,
    table_name      TEXT NOT NULL,
    operation       TEXT NOT NULL CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
    session_user_name TEXT NOT NULL,
    occurred_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    old_data        JSONB,
    new_data        JSONB
);

CREATE INDEX IF NOT EXISTS idx_audit_table_time
    ON audit.table_log (table_schema, table_name, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_occurred_at
    ON audit.table_log (occurred_at DESC);

-- SECURITY DEFINER lets application roles write audited business rows without
-- direct access to the audit schema. A fixed search_path prevents object shadowing.
CREATE OR REPLACE FUNCTION audit.capture_row_change()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, audit
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO audit.table_log
            (table_schema, table_name, operation, session_user_name, new_data)
        VALUES
            (TG_TABLE_SCHEMA, TG_TABLE_NAME, TG_OP, session_user, to_jsonb(NEW));
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO audit.table_log
            (table_schema, table_name, operation, session_user_name, old_data, new_data)
        VALUES
            (TG_TABLE_SCHEMA, TG_TABLE_NAME, TG_OP, session_user, to_jsonb(OLD), to_jsonb(NEW));
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        INSERT INTO audit.table_log
            (table_schema, table_name, operation, session_user_name, old_data)
        VALUES
            (TG_TABLE_SCHEMA, TG_TABLE_NAME, TG_OP, session_user, to_jsonb(OLD));
        RETURN OLD;
    END IF;
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS audit_users_changes ON public.users;
CREATE TRIGGER audit_users_changes
AFTER INSERT OR UPDATE OR DELETE ON public.users
FOR EACH ROW EXECUTE FUNCTION audit.capture_row_change();

DROP TRIGGER IF EXISTS audit_products_changes ON public.products;
CREATE TRIGGER audit_products_changes
AFTER INSERT OR UPDATE OR DELETE ON public.products
FOR EACH ROW EXECUTE FUNCTION audit.capture_row_change();

DROP TRIGGER IF EXISTS audit_orders_changes ON public.orders;
CREATE TRIGGER audit_orders_changes
AFTER INSERT OR UPDATE OR DELETE ON public.orders
FOR EACH ROW EXECUTE FUNCTION audit.capture_row_change();
